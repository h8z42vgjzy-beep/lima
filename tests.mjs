import test from 'node:test';
import assert from 'node:assert/strict';
import {randomUUID} from 'node:crypto';
import {app} from './test-support.mjs';

test('Registration, authentication, language, privacy, consent, logout and existing chat recovery',async t=>{
 const h=await app(t),a=h.client(),b=h.client(),stranger=h.client();
 const input={name:'NewAccount',password:'TemporaryTest123',adult:true,consent:true,language:'uk',theme:'forest'};
 assert.equal((await a.call('register',{...input,consent:false})).status,400);
 assert.equal((await a.call('register',input,{noHeader:true})).status,403);
 const created=await a.call('register',input);assert.equal(created.status,200);a.id=created.data.user.id;
 assert.equal((await a.call('settings')).data.settings.language,'uk');assert.equal((await a.call('settings')).data.settings.theme,'forest');
 assert.equal((await b.call('register',{...input,name:'newaccount'})).status,409);
 assert.equal((await b.call('register',{...input,name:'OtherAccount'})).status,200);b.id=(await b.call('me')).data.user.id;
 assert.equal((await stranger.call('login',{name:input.name,password:'WrongPassword123'})).status,401);
 assert.equal((await stranger.call('login',{name:input.name,password:input.password})).status,200);
 assert.equal((await stranger.call('me')).data.user.id,a.id);
 await a.call('daily',{});await b.call('daily',{});
 const identity={gender:'Frau',queer:'Ja',orientation:'Lesbisch',identityVisible:false};
 await a.call('profile-update',identity);assert.equal((await b.call('member?id='+a.id)).data.member.orientation,'');
 await a.call('profile-update',{...identity,identityVisible:true});assert.equal((await b.call('member?id='+a.id)).data.member.orientation,'Lesbisch');
 const request=await a.call('request',{target:b.id,expectedCost:200});assert.equal(request.status,201);
 assert.equal((await a.call('message',{request:request.data.request,body:'Pending',sendToken:randomUUID(),expectedCost:5})).status,403);
 assert.equal((await a.call('respond',{request:request.data.request,status:'accepted'})).status,403);
 await b.call('respond',{request:request.data.request,status:'accepted'});
 const msg={request:request.data.request,body:'Ein guter Konter.',sendToken:randomUUID(),expectedCost:5};await a.call('message',msg);
 assert.equal((await b.call('messages?request='+request.data.request)).data.messages[0].body,msg.body);
 await b.call('block',{target:a.id});assert.equal((await a.call('messages?request='+request.data.request)).status,403);
 await b.call('unblock',{target:a.id});assert.equal((await b.call('messages?request='+request.data.request)).status,200);
 assert.equal((await a.call('request',{target:b.id,expectedCost:200})).data.charged,0);
 assert.equal((await a.call('logout',{})).status,200);assert.equal((await a.call('me')).data.user,null);
 assert.equal(h.errors(),'');
});
